from alembic import command
from alembic.config import Config
from alembic.util import AutogenerateDiffsDetected
import pytest


def alembic_config(tmp_path):
    config = Config()
    config.set_main_option("script_location", "migrations")
    config.set_main_option("sqlalchemy.url", f"sqlite:///{tmp_path}/test.db")
    return config


def test_migrations_match_models(tmp_path):
    """Fails if a model changed but nobody wrote a migration for it."""
    config = alembic_config(tmp_path)
    command.upgrade(config, "head")

    try:
        command.check(config)
    except AutogenerateDiffsDetected as error:
        pytest.fail(f"Models and migrations differ. Run `alembic revision --autogenerate`.\n{error}")


def test_migrations_downgrade_to_empty(tmp_path):
    config = alembic_config(tmp_path)
    command.upgrade(config, "head")

    command.downgrade(config, "base")
